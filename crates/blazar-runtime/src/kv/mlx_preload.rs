//! Staged MLX warm-start: `blazar kv import --stage-mlx` parks a
//! converted prompt cache next to the model's KV staging area, and the
//! supervisor arms a tiny venv-side wrapper that pre-loads it into
//! `mlx_lm.server`'s in-memory LRU before the first request.
//!
//! The mlx-lm server keeps its prompt cache purely in memory (verified
//! against the lane's installed `mlx_lm` server: `run()` constructs an
//! `LRUPromptCache` and nothing ever persists it), so unlike the
//! llama.cpp slot-bank or vLLM's FS offload tier there is no on-disk
//! location an importer could write to. The wrapper closes that gap
//! without touching upstream code: it subclasses `LRUPromptCache` so the
//! staged cache is inserted into the trie at construction time - keyed by
//! the exact `(model_path, adapter_path, draft_model_path)` tuple the
//! server will look up per request - and then hands control to the
//! server's own `main()`. `insert_cache(..., cache_type="system")` makes
//! the preload the stickiest eviction class (the LRU pops "assistant"
//! entries first).
//!
//! Stage layout: the data files live in
//! `<data_dir>/kv/mlx/<path_safe(model)>/{cache.safetensors, tokens.json}`
//! (written by the import CLI); the wrapper lives beside the lane shim in
//! the engine dir so the spawned cwd stays identical to a plain shim
//! spawn. The wrapper bakes in the lane venv's python (it must import
//! `mlx`), so it is (re)materialized whenever the engine dir changes.

use std::path::{Path, PathBuf};

/// Environment variable carrying the stage directory to the wrapper.
pub const STAGE_ENV: &str = "BLAZAR_MLX_STAGE";

/// Wrapper script name inside the stage directory.
pub const WRAPPER_NAME: &str = "mlx-server-preload";

/// Cache file name inside the stage directory (mlx-lm
/// `--prompt-cache-file` format, produced by the interchange writer).
pub const CACHE_NAME: &str = "cache.safetensors";

/// Token id file name inside the stage directory.
pub const TOKENS_NAME: &str = "tokens.json";

/// Stage directory for a model: `<data_dir>/kv/mlx/<path_safe(name)>`.
#[must_use]
pub fn stage_dir(data_dir: &Path, model: &str) -> PathBuf {
    data_dir
        .join("kv")
        .join("mlx")
        .join(blazar_core::profile::path_safe(model))
}

/// Whether the stage holds an importable cache (wrapper is rematerialized
/// by the supervisor, so only the data files gate readiness).
#[must_use]
pub fn stage_ready(dir: &Path) -> bool {
    dir.join(CACHE_NAME).is_file() && dir.join(TOKENS_NAME).is_file()
}

/// The venv python an mlx engine dir carries: `venv/bin/python` on Unix,
/// `venv/Scripts/python.exe` on Windows. `server_path` is the lane's
/// `mlx-server` shim, so the venv sits beside it.
#[must_use]
pub fn venv_python(server_path: &Path) -> Option<PathBuf> {
    let dir = server_path.parent()?;
    let python = if cfg!(windows) {
        dir.join("venv").join("Scripts").join("python.exe")
    } else {
        dir.join("venv").join("bin").join("python")
    };
    python.is_file().then_some(python)
}

/// Wrapper script text. The shebang pins the lane venv's python (the
/// script must import `mlx`); argv parsing mirrors `mlx_lm.server`'s own
/// flags (`--model`, `--adapter-path`, `--draft-model`) so the trie key
/// matches the server's `ModelProvider.model_key` tuple exactly.
#[must_use]
pub fn wrapper_script(python: &Path) -> String {
    use std::fmt::Write as _;
    let mut body = String::new();

    let _ = writeln!(body, "#!{}", python.to_string_lossy().replace('\\', "/"));
    // The payload below is plain python - never routed through Rust
    // formatting (its braces are python's own), so placeholders are
    // substituted literally.
    let payload = r#"# blazar mlx warm-start wrapper: preloads a staged prompt cache
# into mlx_lm.server's LRU before serving. Regenerated by the supervisor;
# hand edits are overwritten.
import json
import os
import sys

import mlx_lm.server as srv

stage = os.environ["__BLAZAR_STAGE_ENV__"]


def _flag(name):
    if name in sys.argv:
        i = sys.argv.index(name)
        if i + 1 < len(sys.argv) and not sys.argv[i + 1].startswith("--"):
            return sys.argv[i + 1]
    return None


model_key = (
    _flag("--model"),
    _flag("--adapter-path"),
    _flag("--draft-model"),
)
with open(os.path.join(stage, "__BLAZAR_TOKENS_NAME__")) as f:
    tokens = json.load(f)
cache_path = os.path.join(stage, "__BLAZAR_CACHE_NAME__")

_real_lru = srv.LRUPromptCache


class _PreloadingLRU(_real_lru):
    # The cache arrays must be CREATED on the generation thread: on the
    # GPU backend mlx arrays carry the stream of the thread that built
    # them, and the generation loop evals `c.state` from its own thread
    # (mlx_lm/generate.py prompt path). Loading at import time binds the
    # arrays to the main thread and the first generation dies with
    # "There is no Stream(gpu, 0) in current thread". So __init__ only
    # records the pending stage; the load+insert happens inside the
    # generation thread on its first _generate pass, before any request
    # prompt is evaluated.
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._blazar_stage_pending = (model_key, tokens, cache_path)


_real_generate = srv.ResponseGenerator._generate


def _preloading_generate(self):
    pending = getattr(self.prompt_cache, "_blazar_stage_pending", None)
    if pending is not None:
        key, stage_tokens, stage_cache_path = pending
        from mlx_lm.models.cache import load_prompt_cache

        cache = load_prompt_cache(stage_cache_path)
        self.prompt_cache.insert_cache(key, stage_tokens, cache, cache_type="system")
        self.prompt_cache._blazar_stage_pending = None
        print(
            "[blazar] preloaded {} tokens into the mlx prompt cache".format(
                len(stage_tokens)
            ),
            flush=True,
        )
    return _real_generate(self)


srv.LRUPromptCache = _PreloadingLRU
srv.ResponseGenerator._generate = _preloading_generate
srv.main()
"#;
    body.push_str(
        &payload
            .replace("__BLAZAR_STAGE_ENV__", STAGE_ENV)
            .replace("__BLAZAR_TOKENS_NAME__", TOKENS_NAME)
            .replace("__BLAZAR_CACHE_NAME__", CACHE_NAME),
    );
    body
}

/// Materialize (or refresh) the wrapper beside the lane shim (the engine
/// directory - keeping the spawn cwd identical to a plain shim spawn).
/// Write-if-different keeps mtimes stable across spawns; the executable
/// bit is set on Unix. Returns the wrapper path.
pub fn materialize_wrapper(dir: &Path, python: &Path) -> std::io::Result<PathBuf> {
    use std::io::Write as _;
    std::fs::create_dir_all(dir)?;
    let wrapper = dir.join(WRAPPER_NAME);
    let text = wrapper_script(python);
    let fresh = std::fs::read_to_string(&wrapper).map(|current| current != text);
    if fresh.unwrap_or(true) {
        let mut f = std::fs::File::create(&wrapper)?;
        f.write_all(text.as_bytes())?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&wrapper, std::fs::Permissions::from_mode(0o755))?;
        }
    }
    Ok(wrapper)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    #[allow(non_snake_case)]
    fn unit__stage_dir__is_path_safe_under_the_kv_root() {
        let dir = stage_dir(Path::new("/data"), "qwen2.5-1.5b-instruct");
        assert!(dir.starts_with(Path::new("/data/kv/mlx")));
        assert!(dir.to_string_lossy().contains("qwen2.5-1.5b-instruct-"));
    }

    #[test]
    #[allow(non_snake_case)]
    fn unit__stage_ready__demands_both_stage_files() {
        let tmp = tempfile::tempdir().unwrap();
        let dir = tmp.path().join("stage");
        assert!(!stage_ready(&dir));
        std::fs::create_dir_all(&dir).unwrap();
        assert!(!stage_ready(&dir));
        std::fs::write(dir.join(CACHE_NAME), b"x").unwrap();
        assert!(!stage_ready(&dir));
        std::fs::write(dir.join(TOKENS_NAME), b"[]").unwrap();
        assert!(stage_ready(&dir));
    }

    #[test]
    #[allow(non_snake_case)]
    fn unit__wrapper_script__pins_the_venv_python_and_the_server_flow() {
        let text = wrapper_script(Path::new("/engines/mlx-0.32.2/venv/bin/python"));
        assert!(text.starts_with("#!/engines/mlx-0.32.2/venv/bin/python\n"));
        assert!(text.contains("import mlx_lm.server as srv"));
        assert!(text.contains("cache_path = os.path.join(stage, \"cache.safetensors\")"));
        assert!(text.contains("_flag(\"--draft-model\")"));
        assert!(text.contains("cache_type=\"system\""));
        assert!(text.contains("srv.LRUPromptCache = _PreloadingLRU"));
        // The load is deferred into the generation thread (GPU stream
        // affinity): the hook must exist and run before the real loop.
        assert!(text.contains("_blazar_stage_pending"));
        assert!(text.contains("srv.ResponseGenerator._generate = _preloading_generate"));
        assert!(text.contains("_real_generate(self)"));
        assert!(text.contains("srv.main()"));
    }

    #[test]
    #[allow(non_snake_case)]
    fn unit__materialize_wrapper__writes_once_and_refreshes_on_change() {
        let tmp = tempfile::tempdir().unwrap();
        let python = if cfg!(windows) {
            Path::new("C:/engines/mlx/venv/Scripts/python.exe").to_path_buf()
        } else {
            Path::new("/engines/mlx/venv/bin/python").to_path_buf()
        };
        let wrapper = materialize_wrapper(tmp.path(), &python).unwrap();
        assert!(wrapper.is_file());
        let first = std::fs::metadata(&wrapper).unwrap().modified().unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(&wrapper).unwrap().permissions().mode();
            assert_eq!(mode & 0o111, 0o111);
        }
        // Same python -> no rewrite.
        materialize_wrapper(tmp.path(), &python).unwrap();
        assert_eq!(
            std::fs::metadata(&wrapper).unwrap().modified().unwrap(),
            first
        );
        // Different python -> rewritten.
        let other = Path::new("/engines/mlx-0.33.0/venv/bin/python");
        materialize_wrapper(tmp.path(), other).unwrap();
        let text = std::fs::read_to_string(&wrapper).unwrap();
        assert!(text.contains("mlx-0.33.0"));
    }
}
